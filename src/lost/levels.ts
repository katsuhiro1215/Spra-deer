// WORLD 7「鹿のまいご探し」の面(設計書 35章)。夜の奈良公園で、ちょうちんを持った Spra が、
// まいごの子鹿を見つけて、お母さん鹿のところへ 連れて帰る(上から見下ろす迷路)。
//
// 地図の文字:
//   # 木(通れない)  ~ 池(通れない)  L 石灯籠(通れない。まわりを照らす)
//   . 道  S Spra のスタート  M お母さん鹿  F まいごの子鹿  c コイン  g ゴールド  p プレミアム  o ろうそく(ちょうちんの火が もどる)
//   l 火の消えた石灯籠(近づくと 火が つく)  s 道ばたの せんべい(子鹿が 食べに 寄り道する)
//   N 2頭目の お母さん鹿  G N の子(F は M の子)

export type LostLevel = {
  id: string; title: string; summary: string;
  intro: string;
  lesson: string;
  /** 地図(1文字 = 1マス。どの行も 同じ長さ) */
  map: string[];
  /** ちょうちんの火が もつ 秒数(0 になると 真っ暗で 失敗) */
  oil: number;
  /** この秒数より早く 帰れたら ★2(はぐれさせずに 帰れたら ★3) */
  par: number;
  /** 方向の 矢じるし: all = 子鹿と お母さん(はじめの面だけ)、mother = 連れているときの お母さんだけ */
  compass?: 'all' | 'mother';
  /** ちょうちんの 照らす半径(ふつうは LBAL.light) */
  light?: number;
  /** 霧: 通った道が 地図に 残らない */
  fog?: boolean;
  /** 見回りの 大きな鹿: 行ったり来たりする 道(マスの [列, 行] の まがり角)と 速さ */
  stags?: { path: [number, number][]; speed?: number }[];
  /** 子鹿に 近づいた・連れて帰る とちゅう などに出す 一言 */
  notes?: Partial<Record<'found' | 'warn' | 'stray', string>>;
};

